#!/usr/bin/env python3
"""表單範本定義 —— 供 _工具/產生表單.py 產出 Word (.docx) 檔案。

每份表單是一個 dict：
    file    輸出檔名（放在 _表單範本/ 底下）
    title   表單標題（印在文件最上方）
    desc    一句話說明
    source  對應的手冊章節（印在文件末尾，方便回查原理）
    blocks  內容區塊清單

區塊型別：
    H(文字)                     一級標題
    P(文字)                     段落
    T(表頭, 資料列, 欄寬)       表格
    F([欄位名, ...])            兩欄式填寫欄

新增表單時請一併更新 `_規劃/手冊升級規劃.md` 第 14-6 節的清單。
"""
from __future__ import annotations

# ── 區塊建構小工具 ────────────────────────────────────────────


def H(text: str) -> dict:
    return {"type": "heading", "text": text}


def P(text: str = "") -> dict:
    return {"type": "para", "text": text}


def T(headers: list[str], rows: list[list[str]], widths: list[int] | None = None) -> dict:
    return {"type": "table", "headers": headers, "rows": rows, "widths": widths}


def F(labels: list[str]) -> dict:
    return {"type": "fields", "labels": labels}


def blanks(n: int, cols: int) -> list[list[str]]:
    """n 列空白欄，供手寫或後續填入。"""
    return [[""] * cols for _ in range(n)]


def numbered(n: int, cols: int, start: int = 1) -> list[list[str]]:
    """第一欄自動編號、其餘留白。"""
    return [[str(start + i)] + [""] * (cols - 1) for i in range(n)]


CHK = "□ 正常　□ 異常　□ 不適用"
CHK_W = [700, 3100, 3200, 1800, 560]
CHK_HDR = ["編號", "檢查項目", "檢查方式／指令", "檢查結果", "備註"]


def checklist(items: list[tuple[str, str]]) -> dict:
    """把 (檢查項目, 檢查方式) 清單轉成勾選表格。"""
    rows = [[str(i + 1), name, how, CHK, ""] for i, (name, how) in enumerate(items)]
    return T(CHK_HDR, rows, CHK_W)


